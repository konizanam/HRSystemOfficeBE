/** "12,345.67" (negative amounts keep their sign). */
export function formatMoney(value: string | null | undefined): string {
  if (value === null || value === undefined || value === '') return '';
  const fixed = dec(value).toFixed(2);
  const negative = fixed.startsWith('-');
  const [whole = '0', cents = '00'] = (negative ? fixed.slice(1) : fixed).split('.');
  return `${negative ? '-' : ''}${whole.replace(/\B(?=(\d{3})+(?!\d))/g, ',')}.${cents}`;
}

function formatQuantity(value: string | null | undefined): string {
  if (value === null || value === undefined || value === '') return '';
  return dec(value).toDecimalPlaces(4).toString();
}

const BORDER = '#E5E7EB';
const TABLE_LAYOUT = {
  hLineWidth: () => 0.5,
  vLineWidth: () => 0.5,
  hLineColor: () => BORDER,
  vLineColor: () => BORDER,
  paddingLeft: () => 4,
  paddingRight: () => 4,
  paddingTop: () => 2,
  paddingBottom: () => 2,
};

function header(company: { name: string; logo: string | null }, title: string, subtitle: string): Content {
  return {
    columns: [
      {
        width: '*',
        stack: [
          { text: company.name, style: 'company' },
          { text: title, style: 'title' },
          { text: subtitle, style: 'subtitle' },
        ],
      },
      company.logo ? { width: 130, image: company.logo, fit: [130, 50], alignment: 'right' } : { text: '' },
    ],
    margin: [0, 0, 0, 10],
  };
}

function detailsTable(pairs: [string, string][]): Content {
  const body: TableCell[][] = [];
  for (let i = 0; i < pairs.length; i += 2) {
    const left = pairs[i] as [string, string];
    const right = pairs[i + 1] ?? ['', ''];
    body.push([
      { text: left[0], style: 'label' },
      { text: left[1] },
      { text: right[0], style: 'label' },
      { text: right[1] },
    ]);
  }
  return { table: { widths: [90, '*', 90, '*'], body }, layout: TABLE_LAYOUT, margin: [0, 0, 0, 10] };
}

const STYLES: TDocumentDefinitions['styles'] = {
  company: { fontSize: 14, bold: true },
  title: { fontSize: 12, bold: true, margin: [0, 2, 0, 0] },
  subtitle: { fontSize: 9, color: '#4B5563' },
  section: { fontSize: 10, bold: true, margin: [0, 6, 0, 3] },
  label: { bold: true, color: '#374151' },
  th: { bold: true, fillColor: '#F3F4F6' },
  total: { bold: true },
  net: { fontSize: 13, bold: true },
  note: { fontSize: 7, color: '#6B7280' },
};

function footer(generatedAt: Date) {
  return (currentPage: number, pageCount: number): Content => ({
    columns: [
      { text: `Generated by PeopleHub on ${formatTimestamp(generatedAt)}`, style: 'note' },
      { text: `Page ${currentPage} of ${pageCount}`, style: 'note', alignment: 'right' },
    ],
    margin: [40, 10, 40, 0],
  });
}

// ───────────── Payslip ─────────────

export interface PayslipPdfLine {
  category: string;
  code: string;
  description: string;
  quantity: string | null;
  rate: string | null;
  amount: string;
  ytdAmount: string | null;
}

export interface PayslipPdfData {
  company: { name: string; logo: string | null };
  employee: {
    name: string;
    employeeCode: string;
    idNumberMasked: string | null;
    jobTitle: string | null;
    department: string | null;
    dateEngaged: string | null;
    companyRule: string;
  };
  period: { description: string; startDate: string; endDate: string; payDate: string | null };
  payRunLabel: string;
  runType: string;
  currency: string;
  bankMasked: string | null;
  lines: PayslipPdfLine[];
  totals: PayslipTotals;
  leave: { leaveType: string; available: string | null; pending: string }[];
  generatedAt: Date;
}

const LINE_SECTIONS = ['EARNING', 'DEDUCTION', 'COMPANY_CONTRIBUTION', 'FRINGE_BENEFIT', 'INFO'] as const;

function lineSection(category: (typeof LINE_SECTIONS)[number], lines: PayslipPdfLine[]): Content[] {
  const own = lines.filter((l) => l.category === category);
  if (own.length === 0 && (category === 'INFO' || category === 'FRINGE_BENEFIT')) return [];
  const body: TableCell[][] = [
    ['Code', 'Description', 'Quantity', 'Rate', 'Amount', 'YTD'].map((t, i) => ({
      text: t,
      style: 'th',
      alignment: i >= 2 ? 'right' : 'left',
    })),
  ];
  for (const l of own) {
    body.push([
      l.code,
      l.description,
      { text: formatQuantity(l.quantity), alignment: 'right' },
      { text: formatQuantity(l.rate), alignment: 'right' },
      { text: category === 'INFO' ? formatQuantity(l.amount) : formatMoney(l.amount), alignment: 'right' },
      { text: formatMoney(l.ytdAmount), alignment: 'right' },
    ]);
  }
  if (own.length === 0) body.push([{ text: 'None', colSpan: 6, style: 'note' }, '', '', '', '', '']);
  if (category !== 'INFO' && own.length > 0) {
    const total = own.reduce((sum, l) => sum.plus(dec(l.amount)), dec(0)).toFixed(2);
    const ytd = own.some((l) => l.ytdAmount !== null)
      ? own.reduce((sum, l) => sum.plus(dec(l.ytdAmount ?? '0')), dec(0)).toFixed(2)
      : null;
    body.push([
      { text: `Total ${PAYSLIP_SECTION_TITLES[category]}`, colSpan: 4, style: 'total' },
      '',
      '',
      '',
      { text: formatMoney(total), alignment: 'right', style: 'total' },
      { text: formatMoney(ytd), alignment: 'right', style: 'total' },
    ]);
  }
  return [
    { text: PAYSLIP_SECTION_TITLES[category], style: 'section' },
    {
      table: { headerRows: 1, widths: [55, '*', 50, 55, 70, 70], body },
      layout: TABLE_LAYOUT,
    },
  ];
}

/**
 * The payslip (section 5.5): company header and logo; employee block (name, code, masked ID, job
 * title, department, date engaged, pay period, masked bank account); Earnings; Deductions;
 * Company Contributions; Fringe Benefits; YTD totals; leave balances; Net Pay.
 */
export function payslipDocument(data: PayslipPdfData): TDocumentDefinitions {
  const p = data.period;
  const content: Content[] = [
    header(data.company, 'Payslip', `${p.description} · ${data.payRunLabel} · ${data.runType}`),
    detailsTable([
      ['Employee', data.employee.name],
      ['Employee Code', data.employee.employeeCode],
      ['ID Number', data.employee.idNumberMasked ?? ''],
      ['Job Title', data.employee.jobTitle ?? ''],
      ['Department', data.employee.department ?? ''],
      ['Date Engaged', formatGridDate(data.employee.dateEngaged)],
      ['Pay Period', `${formatGridDate(p.startDate)} to ${formatGridDate(p.endDate)}`],
      ['Pay Date', formatGridDate(p.payDate)],
      ['Company Rule', data.employee.companyRule],
      ['Bank Account', data.bankMasked ?? ''],
    ]),
  ];
  for (const category of LINE_SECTIONS) content.push(...lineSection(category, data.lines));
  content.push(
    { text: 'YTD Totals', style: 'section' },
    {
      table: {
        widths: ['*', 90],
        body: [
          ['YTD Gross Pay', { text: formatMoney(data.totals.ytdGrossPay), alignment: 'right' }],
          ['YTD Deductions', { text: formatMoney(data.totals.ytdDeductions), alignment: 'right' }],
          ['YTD Net Pay', { text: formatMoney(data.totals.ytdNetPay), alignment: 'right' }],
        ],
      },
      layout: TABLE_LAYOUT,
    },
    { text: 'Leave Balances', style: 'section' },
    {
      table: {
        headerRows: 1,
        widths: ['*', 90, 90],
        body: [
          [
            { text: 'Leave Type', style: 'th' },
            { text: 'Available (Days)', style: 'th', alignment: 'right' },
            { text: 'Pending (Days)', style: 'th', alignment: 'right' },
          ],
          ...(data.leave.length === 0
            ? [[{ text: 'No leave balances', colSpan: 3, style: 'note' }, '', ''] as TableCell[]]
            : data.leave.map((l): TableCell[] => [
                l.leaveType,
                { text: l.available ?? '—', alignment: 'right' },
                { text: l.pending, alignment: 'right' },
              ])),
        ],
      },
      layout: TABLE_LAYOUT,
    },
    {
      table: {
        widths: ['*', 160],
        body: [
          [
            { text: 'Gross Pay', style: 'label' },
            { text: `${data.currency} ${formatMoney(data.totals.grossPay)}`, alignment: 'right' },
          ],
          [
            { text: 'Total Deductions', style: 'label' },
            { text: `${data.currency} ${formatMoney(data.totals.totalDeductions)}`, alignment: 'right' },
          ],
          [
            { text: 'Net Pay', style: 'net' },
            { text: `${data.currency} ${formatMoney(data.totals.netPay)}`, style: 'net', alignment: 'right' },
          ],
        ],
      },
      layout: TABLE_LAYOUT,
      margin: [0, 12, 0, 0],
    },
  );
  return {
    info: {
      title: `Payslip ${data.employee.employeeCode} ${formatCardDate(p.endDate)}`,
      author: 'PeopleHub',
    },
    pageSize: 'A4',
    pageMargins: [40, 40, 40, 50],
    content,
    footer: footer(data.generatedAt),
    styles: STYLES,
  };
}

